/** Rich record → lobby card shape consumed by the storefront UI. */
function toCard(g) {
  const cat = CATEGORY_BY_ID[g.category];
  const studio = STUDIOS[g.studio];
  return {
    id: g.id,
    title: g.name,
    icon: g.glyph,
    hue: cat.hue,
    category: cat.label,
    studio: g.author || studio.name,
    rating: g.rating ?? (g.rtp ? DERIVE.ratingFromRtp(g.rtp) : DERIVE.defaultRating),
    hot: Boolean(g.popular),
    new: Boolean(g.new),
    url: `${DERIVE.gameBasePath}/${g.id}/index.html`,
    cover: DERIVE.coverPath(g.id),
    license: g.license || (studio.inHouse ? LICENSES.inHouse : LICENSES.mit),
    rtp: g.rtp || null,
    volatility: g.volatility || null,
    features: g.features || [],
    description: g.description,
  };
}

