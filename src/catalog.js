function getGamesByCategory(categoryId) {
  if (!categoryId || categoryId === 'all') return GAMES;
  return GAMES.filter((g) => g.category === categoryId);
}

function searchGames(query) {
  const q = String(query || '').toLowerCase().trim();
  if (!q) return GAMES;
  return GAMES.filter(
    (g) =>
      g.name.toLowerCase().includes(q) ||
      (g.description || '').toLowerCase().includes(q) ||
      (g.tags || []).some((t) => t.includes(q)) ||
      (STUDIOS[g.studio]?.name || '').toLowerCase().includes(q),
  );
}

function getGameStats() {
  return {
    total: GAMES.length,
    byCategory: Object.fromEntries(
      CATEGORIES.map((c) => [c.id, GAMES.filter((g) => g.category === c.id).length]),
    ),
    featured: GAMES.filter((g) => g.featured).length,
    popular: GAMES.filter((g) => g.popular).length,
    new: GAMES.filter((g) => g.new).length,
  };
}

