/** Локаль из ?locale=, затем язык документа, затем английский. */
export function detectGameLocale(search = typeof location === "undefined" ? "" : location.search) {
  const requested = new URLSearchParams(search).get("locale");
  const base = String(requested || "").toLowerCase().split("-")[0];
  return GAME_LOCALES.includes(base) ? base : DEFAULT_GAME_LOCALE;
}

/**
 * Переводчик игры. `extra` — словарь строк конкретной игры вида
 * { en: {key: "…"}, ru: {key: "…"} }; недостающие языки падают на английский.
 */
export function createGameI18n(extra = {}, locale = detectGameLocale()) {
  const active = GAME_LOCALES.includes(locale) ? locale : DEFAULT_GAME_LOCALE;
  const dict = {
    ...GAME_MESSAGES_I18N[DEFAULT_GAME_LOCALE],
    ...(extra[DEFAULT_GAME_LOCALE] || {}),
    ...GAME_MESSAGES_I18N[active],
    ...(extra[active] || {}),
  };
  const t = (key, vars) => {
    const value = dict[key];
    if (value === undefined) return key;
    return vars ? value.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : value;
  };
  t.locale = active;
  /** Проставляет тексты по data-i18n="ключ" во всём документе. */
  t.apply = (root = document) => {
    for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
    for (const node of root.querySelectorAll("[data-i18n-label]"))
      node.setAttribute("aria-label", t(node.dataset.i18nLabel));
    if (typeof document !== "undefined") document.documentElement.lang = active;
  };
  return t;
}
