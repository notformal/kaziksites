import fs from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const titles = JSON.parse(
  await fs.readFile(
    path.join(root, "games", "slots-studio", "titles", "index.json"),
    "utf8",
  ),
);
const icons = ["♛", "◆", "★", "●", "☾", "✦", "7", "BAR"];
const records = titles.map((title, index) => ({
  id: title.id,
  title: title.title,
  studio: "Nova Slots Studio",
  category: "Slots",
  icon: icons[index % icons.length],
  slug: title.id,
  engineSlug: "slots-studio",
  titleId: title.id,
  serverGame: true,
  license: "Original",
  volatility: title.volatility,
  bonus: title.mathProfile.bonus.type,
  hot: index % 11 === 0,
  new: index >= titles.length - 12,
  rating: (4 + (index % 10) / 10).toFixed(1),
  hue: (index * 47) % 360,
}));
await fs.writeFile(
  path.join(root, "apps", "lobby", "src", "slot-titles.generated.json"),
  `${JSON.stringify(records, null, 2)}\n`,
);
const definitions = titles.map((title, index) => ({
  id: title.id,
  kind: "slot",
  mathProfileId: `original-slot-${String(index + 1).padStart(3, "0")}`,
  mathVersion: 1,
  math: {
    symbols: title.symbols.map(({ id, kind }) => ({ id, kind })),
    weights: title.mathProfile.weights,
    paytable: title.paytable,
    lines: title.lines,
    bonus: title.mathProfile.bonus,
  },
}));
await fs.writeFile(
  path.join(root, "apps", "api", "src", "slotMath.generated.js"),
  `// Generated by scripts/sync-slot-catalog.mjs. Do not edit.\nexport const SLOT_DEFINITIONS=${JSON.stringify(definitions, null, 2)};\n`,
);
console.log(`Synced ${records.length} slot titles into the lobby catalog.`);
